"""B16: Itinerary export tool — text/WhatsApp format, iCalendar (.ics), and PDF.

All operations are pure Python, defensive, and return dicts.
"""

from datetime import date, datetime, timedelta
import json
import re


def _resolve_trip(trip_id: str = "", session_id: str = "", trip_data: dict = None) -> dict:
    """Helper to fetch trip from dict, or from SQLite memory."""
    if isinstance(trip_data, dict) and trip_data.get("days"):
        return trip_data
    if trip_id or session_id:
        try:
            from memory.trips import get_trip, latest_trip
            if trip_id and session_id:
                res = get_trip(trip_id, session_id=session_id)
                if "error" not in res:
                    return res
            if session_id:
                res = latest_trip(session_id)
                if "error" not in res:
                    return res
        except Exception:
            pass
    if isinstance(trip_data, dict):
        return trip_data
    return {"error": "Trip data or valid session_id/trip_id required"}


def export_itinerary_text(trip_id: str = "", session_id: str = "", trip_data: dict = None) -> dict:
    """Export trip as a WhatsApp-ready, cleanly formatted text message with emojis.

    Args:
        trip_id: Optional trip ID from database.
        session_id: Optional session ID from database.
        trip_data: Optional direct trip dictionary.

    Returns:
        dict with formatted text string and word count.
    """
    try:
        trip = _resolve_trip(trip_id, session_id, trip_data)
        if "error" in trip:
            return trip

        dest = trip.get("destination", "Trip")
        days = trip.get("days", [])
        travelers = trip.get("travelers", 1)
        pace = trip.get("pace", "normal")
        start_date = trip.get("start_date", "")

        lines = [
            f"🎒 *SafarSathi Travel Plan: {dest}*",
            f"📅 Duration: {len(days)} Days | 👥 Travelers: {travelers} | ⚡ Pace: {pace.capitalize()}",
        ]
        if start_date:
            lines.append(f"🗓️ Start Date: {start_date}")
        lines.append("=" * 35)

        for d in days:
            day_num = d.get("day", 1)
            theme = d.get("theme", "")
            theme_str = f" - {theme}" if theme and theme != dest else ""
            lines.append(f"\n📍 *Day {day_num}{theme_str}*")

            slots = d.get("slots", [])
            for s in slots:
                t = s.get("time", "")
                time_str = f"[{t}] " if t and t != "verify" else ""
                place = s.get("place", "Sight")
                duration = s.get("duration_min", 90)
                notes = s.get("notes", "")

                slot_line = f"  • {time_str}*{place}* (~{duration} min)"
                if notes and notes != "verify opening hours and closed days":
                    # Keep notes short
                    short_note = notes.split(";")[0][:60]
                    slot_line += f"\n    ℹ️ {short_note}"
                lines.append(slot_line)

        lines.append("\n" + "=" * 35)
        lines.append("⚠️ *Notes:* Timings & opening hours are approx — please verify at destination.")
        lines.append("🆘 *Emergency Helpline:* Dial 112 | Ambulance: 108")
        lines.append("✨ Generated by *SafarSathi* — Your AI Travel Companion")

        text_content = "\n".join(lines)
        return {
            "format": "text",
            "destination": dest,
            "days_count": len(days),
            "text": text_content,
            "character_count": len(text_content),
        }
    except Exception as exc:
        return {"error": f"Text export failed: {exc}"}


def export_itinerary_ics(trip_id: str = "", session_id: str = "", trip_data: dict = None) -> dict:
    """Export itinerary as standard iCalendar (.ics) string (RFC 5545).

    Compatible with Google Calendar, Apple Calendar, and Outlook.

    Args:
        trip_id: Optional trip ID.
        session_id: Optional session ID.
        trip_data: Optional direct trip dictionary.

    Returns:
        dict with ics string, filename, and event count.
    """
    try:
        trip = _resolve_trip(trip_id, session_id, trip_data)
        if "error" in trip:
            return trip

        dest = trip.get("destination", "Trip")
        days = trip.get("days", [])
        start_date_str = trip.get("start_date", "")

        # Default start date to tomorrow if not specified
        if start_date_str:
            try:
                base_date = date.fromisoformat(start_date_str)
            except Exception:
                base_date = date.today() + timedelta(days=7)
        else:
            base_date = date.today() + timedelta(days=7)

        now_stamp = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")

        ics_lines = [
            "BEGIN:VCALENDAR",
            "VERSION:2.0",
            "PRODID:-//SafarSathi Travel Assistant//EN",
            "CALSCALE:GREGORIAN",
            "METHOD:PUBLISH",
            f"X-WR-CALNAME:SafarSathi - {dest} Trip",
            "X-WR-TIMEZONE:Asia/Kolkata",
        ]

        event_count = 0
        for d in days:
            day_num = d.get("day", 1)
            event_date = base_date + timedelta(days=day_num - 1)
            slots = d.get("slots", [])

            for idx, s in enumerate(slots):
                place = s.get("place", "Sight")
                duration = int(s.get("duration_min", 90))
                time_str = s.get("time", "")

                # Parse time or fallback to slot order
                hour, minute = 9 + (idx * 2), 0
                if time_str and ":" in time_str and time_str != "verify":
                    try:
                        parts = time_str.split(":")
                        hour, minute = int(parts[0]), int(parts[1])
                    except Exception:
                        pass

                start_dt = datetime(event_date.year, event_date.month, event_date.day, hour, minute)
                end_dt = start_dt + timedelta(minutes=duration)

                dtstart = start_dt.strftime("%Y%m%dT%H%M%S")
                dtend = end_dt.strftime("%Y%m%dT%H%M%S")
                uid = f"safarsathi-{dest.lower().replace(' ', '-')}-d{day_num}-s{idx}-{start_dt.strftime('%Y%m%d%H%M')}@safarsathi"

                notes = s.get("notes", "") or "SafarSathi itinerary stop."
                notes_clean = notes.replace("\n", " ").replace(",", "\\,")

                ics_lines.extend([
                    "BEGIN:VEVENT",
                    f"UID:{uid}",
                    f"DTSTAMP:{now_stamp}",
                    f"DTSTART:{dtstart}",
                    f"DTEND:{dtend}",
                    f"SUMMARY:Visit {place} ({dest})",
                    f"DESCRIPTION:Day {day_num} of {dest} trip. {notes_clean}",
                    f"LOCATION:{place}\\, {dest}\\, India",
                    "STATUS:CONFIRMED",
                    "END:VEVENT",
                ])
                event_count += 1

        ics_lines.append("END:VCALENDAR")
        ics_content = "\r\n".join(ics_lines)

        safe_dest = re.sub(r"[^a-zA-Z0-9_-]", "_", dest).lower()
        filename = f"{safe_dest}_trip_itinerary.ics"

        return {
            "format": "ics",
            "destination": dest,
            "filename": filename,
            "event_count": event_count,
            "ics_content": ics_content,
        }
    except Exception as exc:
        return {"error": f"ICS export failed: {exc}"}


def export_itinerary_pdf(trip_id: str = "", session_id: str = "", trip_data: dict = None) -> dict:
    """Export itinerary as PDF if a PDF engine is installed, or provide structured text fallback.

    Args:
        trip_id: Optional trip ID.
        session_id: Optional session ID.
        trip_data: Optional direct trip dictionary.

    Returns:
        dict with status, note, and HTML/text payload.
    """
    try:
        trip = _resolve_trip(trip_id, session_id, trip_data)
        if "error" in trip:
            return trip

        dest = trip.get("destination", "Trip")

        # Check for PDF engines without raising
        pdf_engine_available = False
        engine_name = None
        try:
            import reportlab  # noqa: F401
            pdf_engine_available = True
            engine_name = "reportlab"
        except ImportError:
            try:
                import weasyprint  # noqa: F401
                pdf_engine_available = True
                engine_name = "weasyprint"
            except ImportError:
                pdf_engine_available = False

        text_export = export_itinerary_text(trip_data=trip)

        return {
            "format": "pdf",
            "destination": dest,
            "pdf_engine_available": pdf_engine_available,
            "engine": engine_name or "none",
            "note": (
                "PDF generation engine available." if pdf_engine_available
                else "PDF renderer (reportlab/weasyprint) not installed in current environment; use formatted text or .ics export."
            ),
            "fallback_text": text_export.get("text", ""),
        }
    except Exception as exc:
        return {"error": f"PDF export check failed: {exc}"}


def export_itinerary(
    format_type: str = "text",
    trip_id: str = "",
    session_id: str = "",
    trip_data: dict = None,
) -> dict:
    """Unified exporter for trip itineraries in multiple formats.

    Args:
        format_type: 'text' (WhatsApp/Markdown), 'ics' (Google/Apple Calendar), or 'pdf'.
        trip_id: Optional trip ID.
        session_id: Optional session ID.
        trip_data: Optional trip dictionary.

    Returns:
        dict with export payload in requested format.
    """
    try:
        fmt = str(format_type or "text").strip().lower()
        if fmt == "ics":
            return export_itinerary_ics(trip_id, session_id, trip_data)
        elif fmt == "pdf":
            return export_itinerary_pdf(trip_id, session_id, trip_data)
        else:
            return export_itinerary_text(trip_id, session_id, trip_data)
    except Exception as exc:
        return {"error": f"Export failed: {exc}"}
